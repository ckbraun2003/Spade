Result<void> validate_object_file(const ObjectFile& file) {
    // The scene's per-asset rules and its material list's, the same functions
    // (TD-9).
    if (Result<void> r = detail::validate_asset(file.object, kUnnamed, kSchema); !r) {
        return r;
    }
    if (Result<void> r = detail::validate_materials(file.materials, kMaterialLabel); !r) {
        return r;
    }
    // A library file carries no dead entries. A name the object uses and does
    // not list is a world's, which compose() resolves (SCN-004).
    for (const MaterialDesc& m : file.materials) {
        if (!names(file.object, m.name)) {
            return std::unexpected(invalid("material '" + m.name +
                                           "' is listed, but the object names it nowhere (in collider_materials "
                                           "or visual.material); an object file lists only the materials its "
                                           "object uses"));
        }
    }
    return {};
}

Result<std::string> object_to_yaml(const ObjectFile& file) {
    if (Result<void> r = validate_object_file(file); !r) {
        return std::unexpected(r.error());
    }
    try {
        return emit(file);
    } catch (const std::exception& e) {
        return std::unexpected(Error{Code::internal, std::string("object file emission failed: ") + e.what()});
    }
}

Result<ObjectFile> object_from_yaml(std::string_view text) {
    Result<ObjectFile> file = parse_text(text);
    if (!file) return file;
    if (Result<void> r = validate_object_file(*file); !r) {
        return std::unexpected(r.error());
    }
    return file;
}

Result<ObjectFile> load_object_file(const std::filesystem::path& path) {
    std::string text;
    try {
        std::ifstream in(path, std::ios::binary);
        if (!in) {
            return std::unexpected(Error{Code::io_error, "cannot open object file '" + path_text(path) + "'"});
        }
        text.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
        if (in.bad()) {
            return std::unexpected(Error{Code::io_error, "failed reading object file '" + path_text(path) + "'"});
        }
    } catch (const std::exception& e) {
        return std::unexpected(
            Error{Code::io_error, "failed reading object file '" + path_text(path) + "': " + e.what()});
    }

    Result<ObjectFile> file = object_from_yaml(text);
    if (!file) {
        return std::unexpected(Error{file.error().code, path_text(path) + ": " + file.error().context});
    }
    return file;
}

Result<void> add_object(SceneDesc& scene, const ObjectFile& object, std::string_view name, const SdfPose& pose) {
    if (Result<void> r = validate_object_file(object); !r) {
        return r;
    }

    // The name, by name: assets and vehicles share one namespace (SCN-004).
    // Never renamed: the editor makes names unique.
    const auto taken = [&](std::string_view by) {
        return std::unexpected(invalid("name '" + std::string(name) + "' is taken by " + std::string(by) +
                                       " in the scene; names are unique across assets and vehicles together, "
                                       "and add_object never renames"));
    };
    for (const SceneAsset& a : scene.assets) {
        if (a.name == name) return taken("an asset");
    }
    for (const SceneVehicle& v : scene.vehicles) {
        if (v.name == name) return taken("a vehicle");
    }

    // ALL OR NOTHING: every change is made on a copy.
    SceneDesc next = scene;

    // The materials, in the file's order: an identical one reused, a missing
    // one appended, and every different one named with every differing field.
    std::string conflicts;
    for (const MaterialDesc& m : object.materials) {
        const auto same_name = std::find_if(next.materials.begin(), next.materials.end(),
                                            [&](const MaterialDesc& s) { return s.name == m.name; });
        if (same_name == next.materials.end()) {
            next.materials.push_back(m);
            continue;
        }
        const std::string differs = differences(m, *same_name);
        if (differs.empty()) continue;
        if (!conflicts.empty()) conflicts += "; ";
        conflicts += "material '" + m.name + "': " + differs;
    }
    if (!conflicts.empty()) {
        return std::unexpected(invalid(std::move(conflicts)));
    }

    SceneAsset placed = object.object;
    placed.name = std::string(name);
    placed.pose = pose;
    next.assets.push_back(std::move(placed));

    // The scene's one validator, on the scene it would become.
    if (Result<void> r = validate_scene(next); !r) {
        return r;
    }
    scene = std::move(next);
    return {};
}

