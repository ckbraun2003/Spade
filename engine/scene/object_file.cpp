// Whether the object names `material`, in a node or in its visual.
[[nodiscard]] bool names(const SceneAsset& a, const std::string& material) {
    return a.visual.material == material ||
           std::find(a.collider_materials.begin(), a.collider_materials.end(), material) !=
               a.collider_materials.end();
}

// A float in its shortest round-trip spelling (to_chars `general`, no
// precision, format_float()'s exponent spelling): what a person reads in a
// message, and still distinct for every two values that differ, -0 included.
[[nodiscard]] std::string shortest(float value) {
    char buf[32];
    const std::to_chars_result r = std::to_chars(buf, buf + sizeof(buf), value, std::chars_format::general);
    if (r.ec != std::errc{}) return "?";
    return yaml_text::normalize_exponent(std::string_view(buf, static_cast<std::size_t>(r.ptr - buf)));
}

[[nodiscard]] std::string colour_text(const glm::vec4& c) {
    return shortest(c.x) + " " + shortest(c.y) + " " + shortest(c.z) + " " + shortest(c.w);
}

// A shading's name; a value outside the enumeration (a scene not yet
// validated may hold one) by its number.
[[nodiscard]] std::string shading_text(MaterialShading shading) {
    const uint32_t value = static_cast<uint32_t>(shading);
    if (value < kMaterialShadingCount) return std::string(yaml_text::kShadingNames[value]);
    return "shading " + dec(value);
}

[[nodiscard]] bool same_bits(const glm::vec4& a, const glm::vec4& b) {
    return std::bit_cast<uint32_t>(a.x) == std::bit_cast<uint32_t>(b.x) &&
           std::bit_cast<uint32_t>(a.y) == std::bit_cast<uint32_t>(b.y) &&
           std::bit_cast<uint32_t>(a.z) == std::bit_cast<uint32_t>(b.z) &&
           std::bit_cast<uint32_t>(a.w) == std::bit_cast<uint32_t>(b.w);
}

// Every field in which the object's material (`here`) differs from the
// scene's of the same name, each with both values; empty when they are
// identical. The name is the same by construction.
[[nodiscard]] std::string differences(const MaterialDesc& here, const MaterialDesc& scene) {
    std::string out;
    const auto differs = [&](std::string_view key, const std::string& ours, const std::string& theirs) {
        if (!out.empty()) out += ", ";
        out += std::string(key) + " differs (" + ours + " here, " + theirs + " in the scene)";
    };
    if (!same_bits(here.base_color, scene.base_color)) {
        differs("base_color", colour_text(here.base_color), colour_text(scene.base_color));
    }
    if (here.shading != scene.shading) {
        differs("shading", shading_text(here.shading), shading_text(scene.shading));
    }
    return out;
}

