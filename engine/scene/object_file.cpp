[[nodiscard]] Error invalid(std::string context) {
    return Error{Code::invalid_argument, std::move(context)};
}

// THE ONE MAPPING from an object version to the scene key set its object
// block is read with (object_file.hpp): object_version 1 reads it as scene
// version 3 does, the newest when it was defined. An asset's keys are the same
// in scene versions 1 to 5 (version 4 changed a model's, N5a; version 5 added
// the scene's airflow, N5b); a later scene version that changes them raises
// detail::kAssetKeySetVersion, and this assert then asks for the new keys to
// be gated by version and for a new object_version, mapped here.
constexpr uint32_t kObjectBlockSceneVersion = 3;
static_assert(kObjectFileVersion == 1, "one mapping per object version: map the new version's key set here");
static_assert(kObjectBlockSceneVersion <= kSceneFileVersion,
              "this build reads the scene key set object_version 1 borrows");
static_assert(detail::kAssetKeySetVersion <= kObjectBlockSceneVersion,
              "parse_asset reads an asset key set newer than object_version 1 borrows: gate the new keys by "
              "version, as ModelBlockFormat does, and read object_version 1 with kObjectBlockSceneVersion's");

// Every diagnostic blames the file's own schema (property 3), never the scene
// schema whose key set the object block borrows.
constexpr std::string_view kSchema = "object schema v1";
// The top level's name in a diagnostic.
constexpr std::string_view kTop = "object file";
// An object with no name, in validate_asset()'s "<unnamed> has no name".
constexpr std::string_view kUnnamed = "object";
// A material's label in validate_material()'s messages.
constexpr std::string_view kMaterialLabel = "object file material";

// ===========================================================================
// Emission
// ===========================================================================

// The header's first two lines are the rule and "-- schema version N."; the
// rest follows.
constexpr std::string_view kHeaderRule =
    "# =============================================================================\n";
constexpr std::string_view kFileHeader = R"YAML(#
# WHAT THIS IS: one placeable object -- a prop, an obstacle, a gate, a floor
# tile, a pole, a wall or a primitive -- what Spade's object library holds, and
# what the editor and Kat's builder place in a scene with add_object().
#
# GENERATED by spade::scene::object_to_yaml(). Hand editing is supported: every
# field is validated on load, and re-saving normalizes the file back to this
# canonical form (fixed key order, fixed float spelling, these comments).
#
# UNITS are SI -- metres and radians -- in a right-handed, Y-up frame. FLOATS
# carry 9 significant digits, so every value survives a load and a save bit
# for bit. Quaternions are [w, x, y, z].
#
# NAMES, NEVER INDICES: a visual and a collider's nodes name their materials,
# each one listed under `materials` or a world's.
# =============================================================================
)YAML";

constexpr std::string_view kObjectComment = R"YAML(
# The object: a scene file's per-asset block, key for key. `pose` is the
# object's as the file holds it; add_object() places it at the pose it is
# given instead. `collider.sdf` is the world file's SDF encoding in the
# object's frame, with node_materials by name; no nodes means no collision.
# An empty visual means none.
)YAML";

constexpr std::string_view kMaterialsComment = R"YAML(
# The materials the object names that a world does not ship, in the scene
# file's encoding. Placing the object adds each to the scene's materials, or
# reuses an identical one of the same name.
)YAML";

[[nodiscard]] std::string emit(const ObjectFile& file) {
    std::string out;
    out.reserve(2048);
    out += kHeaderRule;
    out += "# Spade object file -- schema version " + dec(kObjectFileVersion) + ".\n";
    out += kFileHeader;
    out += "\nobject_version: " + dec(kObjectFileVersion) + "\n";

    // The scene's per-asset block, as a mapping.
    out += kObjectComment;
    out += "object:\n";
    detail::emit_asset(out, file.object, "  ", "  ");

    // Written only when there are any: an object of world materials alone is
    // the text it is.
    if (!file.materials.empty()) {
        out += kMaterialsComment;
        out += "materials:\n";
        for (const MaterialDesc& m : file.materials) {
            out += "  - " + yaml_text::material_flow(m) + "\n";
        }
    }
    return out;
}

// ===========================================================================
// Parsing
// ===========================================================================

[[nodiscard]] Result<ObjectFile> parse_file(const YAML::Node& root) {
    if (!root.IsMap()) {
        return std::unexpected(at(root, "an object file's top level must be a mapping with an 'object_version' key"));
    }

    // VERSION FIRST, before the unknown-key sweep (the scene's rule): a later
    // version's keys would otherwise be reported as unknown.
    const Result<YAML::Node> version_node = field(root, "object_version", kTop);
    if (!version_node) return std::unexpected(version_node.error());
    const Result<uint32_t> version = parse_uint<uint32_t>(*version_node, "object_version");
    if (!version) return std::unexpected(version.error());
    if (*version != kObjectFileVersion) {
        return std::unexpected(Error{Code::schema_mismatch, "object file is schema version " + dec(*version) +
                                                                ", this build reads version " +
                                                                dec(kObjectFileVersion) + " only" +
                                                                mark_of(*version_node)});
    }

    if (Result<void> r = yaml_text::check_map(root, kTop, {"object_version", "object", "materials"}, kSchema); !r) {
        return std::unexpected(r.error());
    }

    ObjectFile out{};
    const Result<YAML::Node> object_node = field(root, "object", kTop);
    if (!object_node) return std::unexpected(object_node.error());
    Result<SceneAsset> object = detail::parse_asset(*object_node, "object", kSchema);
    if (!object) return std::unexpected(object.error());
    out.object = std::move(*object);

    // materials: optional, as the writer omits it for an object that brings
    // none; an empty list is none.
    if (has(root, "materials")) {
        const YAML::Node list = root["materials"];
        if (!list.IsSequence()) {
            return std::unexpected(at(list, "materials must be a sequence"));
        }
        for (std::size_t i = 0; i < list.size(); ++i) {
            const Result<MaterialDesc> m = yaml_text::parse_material(list[i], "materials[" + dec(i) + "]", kSchema);
            if (!m) return std::unexpected(m.error());
            out.materials.push_back(*m);
        }
    }
    return out;
}

// yaml-cpp reports every syntax failure by throwing; nothing may leave a Spade
// API that way (the scene file's rule).
[[nodiscard]] Result<ObjectFile> parse_text(std::string_view text) {
    try {
        const YAML::Node root = YAML::Load(std::string(text));
        return parse_file(root);
    } catch (const YAML::Exception& e) {
        return std::unexpected(Error{Code::invalid_argument, std::string(e.what())});
    } catch (const std::exception& e) {
        return std::unexpected(Error{Code::internal, std::string("object file parse failed: ") + e.what()});
    }
}

