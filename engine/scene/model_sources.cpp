// Every diagnostic blames the sidecar's own schema.
constexpr std::string_view kSchema = "model sources schema v1";
constexpr std::string_view kTop = "model sources file";

// The parts' order in the text: the propeller first, as the draft lists them.
constexpr std::array<PartKind, 4> kPartOrder = {PartKind::prop, PartKind::motor, PartKind::esc, PartKind::battery};

// A part kind's library kind: LibraryKind::motor onward, in PartKind's order.
static_assert(static_cast<uint32_t>(LibraryKind::battery) - static_cast<uint32_t>(LibraryKind::motor) ==
                  static_cast<uint32_t>(PartKind::battery),
              "LibraryKind's part kinds are PartKind's, in its order");

// The generated-file comment every sidecar starts with.
constexpr std::string_view kHeader =
    "# =============================================================================\n"
    "# Spade model sources, schema version 1: where each input of one model file\n"
    "# came from, and the files it was built from, each pinned by its hash.\n"
    "# GENERATED by spade::scene::model_sources_to_yaml() beside the model; never\n"
    "# edit it by hand. check_model_sources() refuses it once its model or a part\n"
    "# changes. The format is engine/scene/model_sources.hpp's.\n"
    "# =============================================================================\n";

[[nodiscard]] Error invalid(std::string context) { return Error{Code::invalid_argument, std::move(context)}; }

// A shared rule's refusal, from the reader: its words, then the node's line
// and column.
[[nodiscard]] Error marked(const Error& e, const YAML::Node& node) { return Error{e.code, e.context + mark_of(node)}; }

[[nodiscard]] std::string kind_text(PartKind kind) { return std::string(part_kind_name(kind)); }

// 16 lowercase hex digits, no 0x (PATHS AND HASHES).
[[nodiscard]] std::string hex16(uint64_t value) {
    static constexpr char kHex[] = "0123456789abcdef";
    std::string out;
    out.reserve(16);
    for (int shift = 60; shift >= 0; shift -= 4) out += kHex[(value >> shift) & 0xfu];
    return out;
}

// YYYY-MM-DD with a month of 01-12 and a day of 01-31: the sources registry's
// rule for `retrieved` (library_sources.cpp), for a Kat date.
[[nodiscard]] bool is_date(std::string_view s) {
    if (s.size() != 10 || s[4] != '-' || s[7] != '-') return false;
    for (std::size_t i = 0; i < s.size(); ++i) {
        if (i == 4 || i == 7) continue;
        if (s[i] < '0' || s[i] > '9') return false;
    }
    const int month = (s[5] - '0') * 10 + (s[6] - '0');
    const int day = (s[8] - '0') * 10 + (s[9] - '0');
    return month >= 1 && month <= 12 && day >= 1 && day <= 31;
}

[[nodiscard]] bool is_lower(char c) { return c >= 'a' && c <= 'z'; }
[[nodiscard]] bool is_digit(char c) { return c >= '0' && c <= '9'; }

// An input's key (INPUTS): dotted segments, each [a-z_][a-z0-9_]* and then
// any number of "[<digits>]".
[[nodiscard]] bool is_field_path(std::string_view path) {
    std::size_t i = 0;
    while (true) {
        if (i >= path.size() || !(is_lower(path[i]) || path[i] == '_')) return false;
        ++i;
        while (i < path.size() && (is_lower(path[i]) || is_digit(path[i]) || path[i] == '_')) ++i;
        while (i < path.size() && path[i] == '[') {
            const std::size_t digits = ++i;
            while (i < path.size() && is_digit(path[i])) ++i;
            if (i == digits || i >= path.size() || path[i] != ']') return false;
            ++i;
        }
        if (i == path.size()) return true;
        if (path[i] != '.') return false;
        ++i;
    }
}

[[nodiscard]] std::string path_problem(std::string_view path) {
    return "inputs key '" + std::string(path) +
           "' is not a field path: dotted segments of lower-case letters, digits and '_', each starting with a "
           "letter or '_' and optionally indexed, as in rotors[0].hub.position";
}

