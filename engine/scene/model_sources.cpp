// The registry-free half of check_source_ref() (CITATIONS), in its own words
// (TD-9): the citation against a registry that lists its source as usable, so
// only its grade and its note can refuse it.
[[nodiscard]] Result<void> check_citation(const SourceRef& ref, const std::string& what) {
    SourceRegistry own{};
    if (!ref.source.empty()) {
        Source self{};
        self.id = ref.source;
        self.license = License::facts_cite;
        own.sources.push_back(std::move(self));
    }
    return check_source_ref(own, ref, what);
}

[[nodiscard]] Result<void> check_finite(double value, const std::string& what) {
    if (std::isfinite(value)) return {};
    return std::unexpected(
        invalid(what + " is not finite (" + format_double(value) + "); a sidecar carries finite numbers"));
}

[[nodiscard]] Result<void> check_value(const InputValue& value, const std::string& what) {
    if (const double* number = std::get_if<double>(&value)) return check_finite(*number, what);
    const std::vector<double>& numbers = std::get<std::vector<double>>(value);
    if (numbers.empty()) {
        return std::unexpected(invalid(what + " is an empty sequence: a vector input has at least one number"));
    }
    for (std::size_t i = 0; i < numbers.size(); ++i) {
        if (Result<void> r = check_finite(numbers[i], what + "[" + dec(i) + "]"); !r) return r;
    }
    return {};
}

[[nodiscard]] Result<void> check_kat(const KatProvenance& kat, const std::string& what) {
    if (kat.source.empty()) return std::unexpected(invalid(what + ".source must not be empty"));
    if (kat.confidence.empty()) return std::unexpected(invalid(what + ".confidence must not be empty"));
    if (!kat.date.empty() && !is_date(kat.date)) {
        return std::unexpected(invalid(what + ".date '" + kat.date +
                                       "' must be a date, YYYY-MM-DD: leave the key out when Kat's is undated"));
    }
    return {};
}

[[nodiscard]] Result<void> check_input(const ModelInput& input) {
    if (!is_field_path(input.path)) return std::unexpected(invalid(path_problem(input.path)));
    const std::string what = "inputs." + input.path;
    if (Result<void> r = check_value(input.value, what + ".value"); !r) return r;
    if (Result<void> r = check_citation(input.ref, what); !r) return r;
    if (input.kat) {
        if (Result<void> r = check_kat(*input.kat, what + ".kat"); !r) return r;
    }
    return {};
}

[[nodiscard]] Result<void> check_check(const ModelCheck& check, const std::string& what) {
    if (check.test.empty()) return std::unexpected(invalid(what + ".test must not be empty"));
    if (Result<void> r = check_finite(check.reference, what + ".reference"); !r) return r;
    if (check.unit.empty()) {
        return std::unexpected(invalid(what + ".unit must not be empty: \"1\" for a pure number"));
    }
    if (Result<void> r = check_citation(check.ref, what); !r) return r;
    if (check.band) {
        const auto [lo, hi] = *check.band;
        if (Result<void> r = check_finite(lo, what + ".band[0]"); !r) return r;
        if (Result<void> r = check_finite(hi, what + ".band[1]"); !r) return r;
        if (!(lo <= hi)) {
            return std::unexpected(invalid(what + ".band [" + format_double(lo) + ", " + format_double(hi) +
                                           "] has lo above hi"));
        }
    } else if (!check.report_only) {
        return std::unexpected(invalid(what + " has no band but is not report_only: a banded check needs [lo, hi]"));
    }
    return {};
}

// Non-empty strings, none twice.
[[nodiscard]] Result<void> check_texts(const std::vector<std::string>& texts, std::string_view key) {
    for (std::size_t i = 0; i < texts.size(); ++i) {
        const std::string what = std::string(key) + "[" + dec(i) + "]";
        if (texts[i].empty()) return std::unexpected(invalid(what + " must not be empty"));
        for (std::size_t j = 0; j < i; ++j) {
            if (texts[j] == texts[i]) {
                return std::unexpected(invalid(what + " '" + texts[i] + "' is " + std::string(key) + "[" + dec(j) +
                                               "] again: each is listed once"));
            }
        }
    }
    return {};
}

// Where `kind` stands in kPartOrder, or kPartOrder.size() for no kind.
[[nodiscard]] std::size_t order_of(PartKind kind) {
    std::size_t k = 0;
    while (k < kPartOrder.size() && kPartOrder[k] != kind) ++k;
    return k;
}

// The order rule's words, the writer's and the reader's alike: `kind` came
// after `before`, which kPartOrder puts first (or they are the same kind).
[[nodiscard]] std::string out_of_order(PartKind kind, PartKind before) {
    return "parts lists the " + kind_text(kind) + " after the " + kind_text(before) +
           ": the order is prop, motor, esc, battery, each kind at most once";
}

[[nodiscard]] Result<void> check_parts(const std::vector<PinnedPart>& parts) {
    for (std::size_t i = 0; i < parts.size(); ++i) {
        const std::size_t k = order_of(parts[i].kind);
        if (k == kPartOrder.size()) {
            return std::unexpected(invalid("parts[" + dec(i) + "] has kind " +
                                           dec(static_cast<uint32_t>(parts[i].kind)) +
                                           ", which is not one of the four"));
        }
        const std::string kind = kind_text(parts[i].kind);
        if (i > 0 && k <= order_of(parts[i - 1].kind)) {
            return std::unexpected(invalid(out_of_order(parts[i].kind, parts[i - 1].kind)));
        }
        if (parts[i].file.empty()) return std::unexpected(invalid("parts." + kind + ".file must not be empty"));
    }
    return {};
}

[[nodiscard]] Result<void> validate(const ModelSources& s) {
    if (s.model.file.empty()) return std::unexpected(invalid("model.file must not be empty"));
    if (s.built_by.empty()) return std::unexpected(invalid("built_by must not be empty"));
    if (Result<void> r = check_parts(s.parts); !r) return r;
    for (std::size_t i = 0; i < s.inputs.size(); ++i) {
        if (Result<void> r = check_input(s.inputs[i]); !r) return r;
        for (std::size_t j = 0; j < i; ++j) {
            if (s.inputs[j].path == s.inputs[i].path) {
                return std::unexpected(
                    invalid("inputs has '" + s.inputs[i].path + "' twice: each input is listed once"));
            }
        }
    }
    if (Result<void> r = check_texts(s.not_carried, "not_carried"); !r) return r;
    for (std::size_t i = 0; i < s.checks.size(); ++i) {
        if (Result<void> r = check_check(s.checks[i], "checks[" + dec(i) + "]"); !r) return r;
    }
    return check_texts(s.assumptions, "assumptions");
}

