[[nodiscard]] std::string pinned_text(const std::string& file, uint64_t hash) {
    return "{file: " + quote_yaml(file) + ", hash: " + quote_yaml(hex16(hash)) + "}";
}

[[nodiscard]] std::string number_list(const double* values, std::size_t n) {
    std::string out = "[";
    for (std::size_t i = 0; i < n; ++i) {
        if (i != 0) out += ", ";
        out += format_double(values[i]);
    }
    return out + "]";
}

[[nodiscard]] std::string value_text(const InputValue& value) {
    if (const double* number = std::get_if<double>(&value)) return format_double(*number);
    const std::vector<double>& numbers = std::get<std::vector<double>>(value);
    return number_list(numbers.data(), numbers.size());
}

// A citation's keys, each after ", ": source and note only when given.
[[nodiscard]] std::string citation_text(const SourceRef& ref) {
    std::string out;
    if (!ref.source.empty()) out += ", source: " + quote_yaml(ref.source);
    out += ", grade: " + std::string(grade_name(ref.grade));
    if (!ref.note.empty()) out += ", note: " + quote_yaml(ref.note);
    return out;
}

void append_texts(std::string& out, std::string_view key, const std::vector<std::string>& texts) {
    out += std::string(key) + ":";
    if (texts.empty()) {
        out += " []\n";
        return;
    }
    out += "\n";
    for (const std::string& t : texts) out += "  - " + quote_yaml(t) + "\n";
}

[[nodiscard]] std::string emit(const ModelSources& s) {
    std::string out(kHeader);
    out += "\nmodel_sources_version: " + dec(kModelSourcesVersion) + "\n";
    out += "model: " + pinned_text(s.model.file, s.model.hash) + "\n";
    out += "built_by: " + quote_yaml(s.built_by) + "\n";
    if (s.parts.empty()) {
        out += "parts: {}\n";
    } else {
        out += "parts:\n";
        for (const PinnedPart& p : s.parts) out += "  " + kind_text(p.kind) + ": " + pinned_text(p.file, p.hash) + "\n";
    }
    if (s.inputs.empty()) {
        out += "inputs: {}\n";
    } else {
        out += "inputs:\n";
        for (const ModelInput& in : s.inputs) {
            out += "  " + quote_yaml(in.path) + ": {value: " + value_text(in.value) + citation_text(in.ref);
            if (in.kat) {
                out += ", kat: {source: " + quote_yaml(in.kat->source) + ", confidence: " +
                       quote_yaml(in.kat->confidence);
                if (!in.kat->date.empty()) out += ", date: " + quote_yaml(in.kat->date);
                out += "}";
            }
            out += "}\n";
        }
    }
    append_texts(out, "not_carried", s.not_carried);
    if (s.checks.empty()) {
        out += "checks: []\n";
    } else {
        out += "checks:\n";
        for (const ModelCheck& c : s.checks) {
            out += "  - {test: " + quote_yaml(c.test) + ", reference: " + format_double(c.reference) +
                   ", unit: " + quote_yaml(c.unit) + citation_text(c.ref);
            if (c.band) out += ", band: " + number_list(c.band->data(), c.band->size());
            out += std::string(", report_only: ") + (c.report_only ? "true" : "false") + "}\n";
        }
    }
    append_texts(out, "assumptions", s.assumptions);
    if (!s.caveat.empty()) out += "caveat: " + quote_yaml(s.caveat) + "\n";
    return out;
}

