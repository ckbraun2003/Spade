Result<void> validate_model_file(const ModelFile& file) {
    // The scene's per-model rules, the same function (TD-9).
    if (Result<void> r = detail::validate_model(file.model, kSchema, kKind); !r) {
        return r;
    }
    return {};
}

Result<std::string> model_to_yaml(const ModelFile& file) {
    if (Result<void> r = validate_model_file(file); !r) {
        return std::unexpected(r.error());
    }
    if (Result<void> r = detail::check_model_writable(file.model, kKind); !r) {
        return std::unexpected(r.error());
    }
    try {
        return emit(file);
    } catch (const std::exception& e) {
        return std::unexpected(Error{Code::internal, std::string("model file emission failed: ") + e.what()});
    }
}

Result<ModelFile> model_from_yaml(std::string_view text, const std::filesystem::path& base_dir) {
    Result<ModelFile> file = parse_text(text, base_dir);
    if (!file) return file;
    if (Result<void> r = validate_model_file(*file); !r) {
        return std::unexpected(r.error());
    }
    return file;
}

Result<ModelFile> load_model_file(const std::filesystem::path& path) {
    std::string text;
    try {
        std::ifstream in(path, std::ios::binary);
        if (!in) {
            return std::unexpected(Error{Code::io_error, "cannot open model file '" + path_text(path) + "'"});
        }
        text.assign(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
        if (in.bad()) {
            return std::unexpected(Error{Code::io_error, "failed reading model file '" + path_text(path) + "'"});
        }
    } catch (const std::exception& e) {
        return std::unexpected(
            Error{Code::io_error, "failed reading model file '" + path_text(path) + "': " + e.what()});
    }

    // A mesh part's sidecar is relative to the model file's directory, "."
    // for a bare file name.
    const std::filesystem::path base_dir = path.has_parent_path() ? path.parent_path() : std::filesystem::path(".");
    Result<ModelFile> file = model_from_yaml(text, base_dir);
    if (!file) {
        return std::unexpected(Error{file.error().code, path_text(path) + ": " + file.error().context});
    }
    return file;
}

Result<void> add_model(SceneDesc& scene, const ModelFile& file, std::string_view model_name) {
    if (Result<void> r = validate_model_file(file); !r) {
        return r;
    }

    // NO MESH PARTS (N3, the lead's ruling): a mesh part's mesh_file names its
    // sidecar relative to the MODEL file, and a scene reads it relative to the
    // SCENE file, so placing one would need its sidecars copied beside the
    // scene, which nothing does yet.
    for (const vehicles::PartDesc& p : file.model.parts) {
        if (p.mesh) {
            return std::unexpected(Error{Code::invalid_argument,
                                         "add_model: model '" + file.model.name +
                                             "' has mesh parts; their sidecars would need copying beside the "
                                             "scene, which is not yet supported"});
        }
    }

    // The name, by name: a model's name is unique within the scene's models
    // (SCN-004), its own namespace. Never renamed: the editor makes names
    // unique.
    for (const vehicles::ModelType& m : scene.models) {
        if (m.name == model_name) {
            return std::unexpected(Error{Code::invalid_argument,
                                         "model name '" + std::string(model_name) +
                                             "' is taken by a model in the scene; model names are unique within "
                                             "models, and add_model never renames"});
        }
    }

    // ALL OR NOTHING: the change is made on a copy. The model is copied whole,
    // so its chain (model.propulsion) comes with it.
    SceneDesc next = scene;
    vehicles::ModelType placed = file.model;
    placed.name = std::string(model_name);
    next.models.push_back(std::move(placed));

    // The scene's one validator, on the scene it would become.
    if (Result<void> r = validate_scene(next); !r) {
        return r;
    }
    scene = std::move(next);
    return {};
}

