// THE ONE MAPPING from a model version to the scene key set its model block
// is read with (model_file.hpp): model_version 1 reads it as scene version 4
// does, the newest, which carries everything (parts, mesh parts, the chain).
// The key set stays that version's: a later scene version that adds a model
// key is read by a new model_version, mapped here.
//
// MOVED FROM 3 TO 4 with N5a (the lead's ruling, 2026-10-19), the one change
// to model_version 1's text: the chain moved from a top-level `propulsion:`
// into the model block, as the model's own last key. No model file had been
// committed in N1's layout; one is refused, its `propulsion` an unknown key.
constexpr uint32_t kModelBlockSceneVersion = 4;
static_assert(kModelFileVersion == 1, "one mapping per model version: map the new version's key set here");
static_assert(kModelBlockSceneVersion <= kSceneFileVersion,
              "this build reads the scene key set model_version 1 borrows");

// Every diagnostic blames the file's own schema (property 3), never the scene
// schema whose key set the model block borrows.
constexpr std::string_view kSchema = "model schema v1";
// What a sidecar's path is relative to, and the loader that knows it.
constexpr std::string_view kKind = "model";
// The top level's name in a diagnostic.
constexpr std::string_view kTop = "model file";

[[nodiscard]] detail::ModelBlockFormat block_format() {
    return detail::ModelBlockFormat{kModelBlockSceneVersion, kSchema, kKind};
}

// ===========================================================================
// Emission
// ===========================================================================

// The header's first two lines are the rule and "-- schema version N."; the
// rest follows.
constexpr std::string_view kHeaderRule =
    "# =============================================================================\n";
constexpr std::string_view kFileHeader = R"YAML(#
# WHAT THIS IS: one vehicle model, and optionally its propulsion chain -- what
# the editor adds a drone from, what Spade's model library holds, and what an
# analysis case names.
#
# GENERATED by spade::scene::model_to_yaml(). Hand editing is supported: every
# field is validated on load, and re-saving normalizes the file back to this
# canonical form (fixed key order, fixed number spelling, these comments).
#
# UNITS are SI -- metres, kilograms, seconds, radians, volts, amperes, ohms,
# henries -- in a right-handed, Y-up frame. FLOATS carry 9 significant digits
# and DOUBLES the fewest that read back to the same value, so every value
# survives a load and a save bit for bit. Quaternions are [w, x, y, z].
# =============================================================================
)YAML";

constexpr std::string_view kModelComment = R"YAML(
# The model: a scene file's per-model block, key for key. `design_to_principal`
# turns the design frame into the principal-axis body frame; `com_offset` is
# the centre of mass from the design origin, in the design frame. Rotor, drag
# and IMU mounts are in the body frame; a part's mount is too, or, on a rotor,
# in that rotor's hub frame at azimuth 0. A mesh part names its .spmesh
# sidecar by a path relative to this file and FNV-1a 64 of the mesh's content.
)YAML";

// The model comment's second paragraph, written only when the model has a
// chain, so a model without one is the text it always was.
constexpr std::string_view kPropulsionComment = R"YAML(#
# Its last key, `propulsion`, is the model's propulsion chain: every field of
# vehicles::PropulsionChain, by its own name. kv is in rad/(s V), not rpm/V;
# battery fields are per cell unless they say pack; the propeller's tables are
# on a uniform grid of advance ratio from j_min to j_max, and ocv_table on a
# uniform state-of-charge grid.
)YAML";

[[nodiscard]] std::string emit(const ModelFile& file) {
    std::string out;
    out.reserve(4096);
    out += kHeaderRule;
    out += "# Spade model file -- schema version " + dec(kModelFileVersion) + ".\n";
    out += kFileHeader;
    out += "\nmodel_version: " + dec(kModelFileVersion) + "\n";

    // The scene's per-model block, as a mapping, its chain the last key
    // (emit_model writes it when set).
    out += kModelComment;
    if (file.model.propulsion) out += kPropulsionComment;
    out += "model:\n";
    detail::emit_model(out, file.model, "  ", "  ");
    return out;
}

// ===========================================================================
// Parsing
// ===========================================================================

[[nodiscard]] Result<ModelFile> parse_file(const YAML::Node& root, const std::filesystem::path& base_dir) {
    if (!root.IsMap()) {
        return std::unexpected(at(root, "a model file's top level must be a mapping with a 'model_version' key"));
    }

    // VERSION FIRST, before the unknown-key sweep (the scene's rule): a later
    // version's keys would otherwise be reported as unknown.
    const Result<YAML::Node> version_node = field(root, "model_version", kTop);
    if (!version_node) return std::unexpected(version_node.error());
    const Result<uint32_t> version = parse_uint<uint32_t>(*version_node, "model_version");
    if (!version) return std::unexpected(version.error());
    if (*version != kModelFileVersion) {
        return std::unexpected(Error{Code::schema_mismatch, "model file is schema version " + dec(*version) +
                                                                ", this build reads version " +
                                                                dec(kModelFileVersion) + " only" +
                                                                mark_of(*version_node)});
    }

    // The chain is the model block's (N5a): a top-level `propulsion` is unknown.
    if (Result<void> r = yaml_text::check_map(root, kTop, {"model_version", "model"}, kSchema); !r) {
        return std::unexpected(r.error());
    }

    ModelFile out{};
    const Result<YAML::Node> model_node = field(root, "model", kTop);
    if (!model_node) return std::unexpected(model_node.error());
    Result<vehicles::ModelType> model = detail::parse_model(*model_node, "model", block_format(), base_dir);
    if (!model) return std::unexpected(model.error());
    out.model = std::move(*model);
    return out;
}

// yaml-cpp reports every syntax failure by throwing; nothing may leave a Spade
// API that way (the scene file's rule).
[[nodiscard]] Result<ModelFile> parse_text(std::string_view text, const std::filesystem::path& base_dir) {
    try {
        const YAML::Node root = YAML::Load(std::string(text));
        return parse_file(root, base_dir);
    } catch (const YAML::Exception& e) {
        return std::unexpected(Error{Code::invalid_argument, std::string(e.what())});
    } catch (const std::exception& e) {
        return std::unexpected(Error{Code::internal, std::string("model file parse failed: ") + e.what()});
    }
}

