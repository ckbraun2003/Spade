#pragma once

// ---------------------------------------------------------------------------
// part_stand_in/stand_in.hpp -- spade_part_stand_in (L88l): stand-in boxes for a part whose meshes live in the local part store (L88b), so the
// public repository's library still shows the drone's layout where the store is absent.
//
// THE RULE (library contract): a part with `meshes` draws them when the store has them, else its `shapes`. Physics and compile use the meshes only
// and refuse `store_file_missing` without the store: a stand-in for physics would give one machine's inertia a different value from another's, and
// the same inputs must give the same results. A part with shapes and no meshes uses its shapes for both.
//
// What the tool writes, for each part with store meshes: one AXIS-ALIGNED box per object (a glTF: per material) in the part's own frame, skipping
// objects whose box holds under `min_volume_m3` (0.2 cm3; the largest is kept when all are under it, so `shapes` is never empty), appended to the
// part's text after a marker line, with a citation `sources: shapes: {source: <the part's source id>, grade: derived, note: ...}` (the blocks
// reader ignores citation paths it does not own, so no field is new). Run again, it replaces its own block: the text before the marker is the
// part's own and is never touched.
// ---------------------------------------------------------------------------

#include <cstddef>
#include <expected>
#include <filesystem>
#include <string>
#include <string_view>
#include <vector>

#include <glm/vec3.hpp>

namespace spade::stand_in {

// The line that starts the generated block; everything from it to the end of the file is the tool's.
inline constexpr std::string_view kMarker = "# part_stand_in: begin (generated by tools/part_stand_in from the part store; stand-in boxes, drawn only when the store is absent; do not edit)";

struct Options {
    double min_volume_m3 = 2e-7;               // 0.2 cm3
    std::vector<std::string> skip_materials{};  // a glTF submesh whose material name ends with one of these is left out (a part hidden in the drawing, a bell)
};

struct Box {
    glm::dvec3 center{0.0};
    glm::dvec3 size{0.0};
};

// The boxes of one store file: an .spmesh gives one, a .gltf one per submesh (material). The error is a message naming the file.
[[nodiscard]] std::expected<std::vector<Box>, std::string> boxes_of_file(const std::filesystem::path& file, const Options& options);

struct StandInResult {
    std::string text{};         // the part's text with the generated block (unchanged for a part with no meshes)
    std::size_t boxes = 0;      // the shapes written
    std::size_t skipped = 0;    // the objects left out for being under the limit
};

// `part_text` is a blocks-only part file; `store` the part store (<store>/<sha256>/<file>). Refused, with a message: the text is not a part, it has no
// source (the citation needs one), its last top-level key is not `sources`, a store file is missing or unreadable, or the result does not read back.
[[nodiscard]] std::expected<StandInResult, std::string> add_stand_in(std::string_view part_text, const std::filesystem::path& store, const Options& options);

}  // namespace spade::stand_in
