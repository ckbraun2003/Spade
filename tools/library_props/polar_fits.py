#!/usr/bin/env python3
"""Turn polar_fits.json (the actuator line's per-prop polar, L72k B1) into
tests/library_polar_fits.gen.hpp.

The fits are not derived from files here: they are the output of Physics'
fitting runs (b1-polar-fits record), kept as committed data so the part files
and the tests read one table. This tool only checks it and writes it as C++.
tests/test_library_props.cpp recomputes the hash of this file and of the json
from the source tree (FNV-1a 64, CRLF read as LF), so an edit to either without
re-running this tool fails the suite.

    python tools/library_props/polar_fits.py --fits tools/library_props/polar_fits.json \
        --out tests/library_polar_fits.gen.hpp

stdlib only. A fit is refused by name if its id repeats, a number is not finite,
cd_scale is not above 0, or alpha_0_deg is outside (-30, 10).
"""

import argparse
import json
import math
import os
import sys


class ToolError(Exception):
    """A refusal, naming the fit."""


def fnv1a64(data):
    """FNV-1a 64 of `data`, CRLF read as LF."""
    h = 0xCBF29CE484222325
    for byte in data.replace(b"\r\n", b"\n"):
        h ^= byte
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def hash_file(path):
    with open(path, "rb") as f:
        return fnv1a64(f.read())


def number(x):
    """A double literal that reads back bit for bit."""
    s = repr(float(x))
    return s if any(c in s for c in ".en") else s + ".0"


def text_literal(s):
    if not s.isascii() or any(c in s for c in '\\"\n\r'):
        raise ToolError(f"a note must be plain ASCII with no quote, backslash or newline: {s!r}")
    return '"' + s + '"'


def read_fits(path):
    try:
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
    except (OSError, ValueError) as e:
        raise ToolError(f"{os.path.basename(path)}: cannot be read ({e})") from None
    fits = doc.get("fits")
    if not isinstance(fits, list) or not fits:
        raise ToolError("polar_fits.json: 'fits' must be a non-empty list")
    seen = set()
    for f in fits:
        name = f.get("id")
        if not isinstance(name, str) or not name:
            raise ToolError("a fit has no id")
        if name in seen:
            raise ToolError(f"{name}: listed twice")
        seen.add(name)
        for key in ("alpha_0_deg", "cd_scale"):
            v = f.get(key)
            if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
                raise ToolError(f"{name}: {key} must be a finite number")
        if not f["cd_scale"] > 0.0:
            raise ToolError(f"{name}: cd_scale must be above 0, found {f['cd_scale']}")
        if not -30.0 < f["alpha_0_deg"] < 10.0:
            raise ToolError(f"{name}: alpha_0_deg {f['alpha_0_deg']} is outside (-30, 10)")
        if not isinstance(f.get("fit"), str) or not f["fit"]:
            raise ToolError(f"{name}: 'fit' (the conditions and the match) must be a non-empty string")
    return fits


HEADER = """\
// =============================================================================
// GENERATED by tools/library_props/polar_fits.py -- do not edit; re-run it.
// The actuator line's per-prop polar (L72k B1): alpha_0 and the drag scale
// fitted through the line with the tip correction ON, against UIUC's static
// C_T and C_Q. Valid only at the kernel width and resolution each was fitted
// at (its `fit` text) and with the tip correction on.
// =============================================================================
#pragma once

#include <array>
#include <cstdint>
#include <string_view>

namespace spade::test::library_polar_fits {

// FNV-1a 64 of the tool and of its table, CRLF read as LF.
// tests/test_library_props.cpp recomputes both from the source tree.
"""

TYPES = """
struct Fit {
    std::string_view id;  // a library prop's id (tests/library_props.gen.hpp)
    double alpha_0_deg;
    double cd_scale;
    std::string_view fit;  // the conditions and the match, for the part file's citation
};
"""


def generate(fits_path):
    fits = read_fits(fits_path)
    out = [HEADER.rstrip("\n")]
    out.append(f"inline constexpr std::uint64_t kToolHash = 0x{hash_file(os.path.abspath(__file__)):016x}ull;  // polar_fits.py")
    out.append(f"inline constexpr std::uint64_t kFitsHash = 0x{hash_file(fits_path):016x}ull;  // polar_fits.json")
    out.append(TYPES.rstrip("\n"))
    out.append("")
    out.append(f"inline constexpr std::array<Fit, {len(fits)}> kFits{{{{")
    for f in fits:
        out.append("    {")
        out.append(f"        {text_literal(f['id'])},")
        out.append(f"        {number(f['alpha_0_deg'])},")
        out.append(f"        {number(f['cd_scale'])},")
        out.append(f"        {text_literal(f['fit'])},")
        out.append("    },")
    out.append("}};")
    out.append("")
    out.append("}  // namespace spade::test::library_polar_fits")
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write tests/library_polar_fits.gen.hpp from polar_fits.json.")
    parser.add_argument("--fits", required=True, help="the fits table (tools/library_props/polar_fits.json)")
    parser.add_argument("--out", required=True, help="the header to write")
    args = parser.parse_args(argv)
    try:
        text = generate(args.fits)
    except ToolError as e:
        print("polar_fits: " + str(e), file=sys.stderr)
        return 1
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
